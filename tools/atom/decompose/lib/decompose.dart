/// Render the merged journey [graph] — `graph.journey.json` + `GRAPH.md`.
Map<String, String> renderJourneyGraph(JourneyGraph graph) {
  final b = StringBuffer()
    ..writeln('# journeys — the whole graph')
    ..writeln()
    ..writeln('> Auto-generated by `tools/atom/decompose` (journeys). Read-only.')
    ..writeln('> Navigator 1.0 imperative — recovered from the pushes, not a route table.')
    ..writeln()
    ..writeln('- **nodes (screens):** ${graph.nodes.length}')
    ..writeln('- **edges (transitions):** ${graph.edges.length}')
    ..writeln('- **route-addressable:** ${graph.nodes.values.where((n) => n.routeAddressable).length}')
    ..writeln('- **provider-swap (Navigator-invisible):** ${graph.edges.where((e) => e.kind == 'provider-swap').length}')
    ..writeln('- **raw-push (off-convention, no route()):** ${graph.edges.where((e) => e.kind == 'raw-push').length}')
    ..writeln('- **dormant (flag-gated):** ${graph.edges.where((e) => e.dormant).length}')
    ..writeln()
    ..writeln('## Bypass surfaces (step 73)')
    ..writeln();
  for (final n in graph.nodes.values.where((n) => n.bypassSurface != null)) {
    b.writeln('- **${n.bypassSurface}** · `${n.screen}`');
  }
  b
    ..writeln()
    ..writeln('## Edges')
    ..writeln()
    ..writeln('| from | → | to | kind | trigger | dormant |')
    ..writeln('|---|---|---|---|---|---|');
  final sorted = [...graph.edges]..sort((a, z) => a.from.compareTo(z.from));
  for (final e in sorted) {
    b.writeln('| `${e.from}` | → | `${e.to}` | ${e.kind} | `${e.trigger}` '
        '| ${e.dormant ? '⚠️ `${e.gate}`' : '—'} |');
  }
  return <String, String>{
    'graph.journey.json': '${_json.convert(graph.toJson())}\n',
    'GRAPH.md': b.toString(),
  };
}

String _journeyMd(JourneyModuleDecomposition m) {
  final b = StringBuffer()
    ..writeln('# ${m.module} — journey decomposition')
    ..writeln()
    ..writeln('> Auto-generated by `tools/atom/decompose` (journeys). Read-only —')
    ..writeln('> re-run the decomposer. Source: `${m.sourcePath}`.')
    ..writeln()
    ..writeln('## Nodes (screens)')
    ..writeln('| screen | line | route()? | returns value? | bypass |')
    ..writeln('|---|---|---|---|---|');
  for (final n in m.nodes) {
    b.writeln('| `${n.screen}` | ${n.line} '
        '| ${n.routeAddressable ? '`route(${n.routeParams})`' : '—'} '
        '| ${n.returnsValue ? '↑ pop-value' : '—'} '
        '| ${n.bypassSurface ?? '—'} |');
  }
  b
    ..writeln()
    ..writeln('## Edges (transitions)');
  if (m.edges.isEmpty) {
    b.writeln('- _none_');
  } else {
    b
      ..writeln('| from | → | to | kind | trigger | params | dormant |')
      ..writeln('|---|---|---|---|---|---|---|');
    for (final e in m.edges) {
      b.writeln('| `${e.from}` | → | `${e.to}` | ${e.kind} | `${e.trigger}` '
          '| ${e.params.isEmpty ? '—' : '`${e.params}`'} '
          '| ${e.dormant ? '⚠️ `${e.gate}`' : '—'} |');
    }
  }
  return b.toString();
}

// ─── primitive decomposition (DECOMP-DEPTH phase P) ───────────────────────────

/// Render every output file for a primitive [module] — `module.prim.json` (the
/// machine table) + one `<module>.prim.md` (the human contract table, step 69).
Map<String, String> renderPrimitiveFiles(PrimitiveModuleDecomposition module) {
  return <String, String>{
    'module.prim.json': '${_json.convert(module.toJson())}\n',
    '${_slug(module.module)}.prim.md': _primMd(module),
  };
}

/// Write [renderPrimitiveFiles] to `<outDir>/<module>/`.
void writePrimitiveOut(PrimitiveModuleDecomposition module, String outDir) {
  final dir = Directory(p.join(outDir, module.module));
  dir.createSync(recursive: true);
  renderPrimitiveFiles(module).forEach((name, contents) {
    File(p.join(dir.path, name)).writeAsStringSync(contents);
  });
}

String _primMd(PrimitiveModuleDecomposition m) {
  final b = StringBuffer()
    ..writeln('# ${m.module} — primitive contracts')
    ..writeln()
    ..writeln('> Auto-generated by `tools/atom/decompose` (primitives). Read-only —')
    ..writeln('> re-run the decomposer. Source: `${m.sourcePath}`.')
    ..writeln()
    ..writeln('> The floor turned from a NAME into a CONTRACT: each row is one')
    ..writeln('> floor-primitive — signature · returns · edge cases · purity.')
    ..writeln()
    ..writeln('| # | primitive | line | signature | returns | pure? |')
    ..writeln('|---|---|---|---|---|---|');
  for (var i = 0; i < m.primitives.length; i++) {
    final pr = m.primitives[i];
    final purity = pr.pure ? '✅ pure' : '❌ ${pr.sideEffect}';
    b.writeln('| ${i + 1} | `${pr.name}` | ${pr.line} | `${pr.signature}` '
        '| `${pr.returns}` | $purity |');
  }
  b
    ..writeln()
    ..writeln('## Edge contracts (step 70 → assertions)')
    ..writeln();
  for (final pr in m.primitives) {
    b.writeln('### `${pr.name}` — `${pr.signature}`');
    if (pr.edges.isEmpty) {
      b.writeln('- _no boundary edges detected (total function)_');
    } else {
      for (final e in pr.edges) {
        b.writeln('- **${e.note}** — _signal_ `${e.signal}`');
      }
    }
    b.writeln();
  }
  return b.toString();
}

String _dataMd(DataModuleDecomposition m, DataEntity e) {
  String flags(DataField f) => [
        if (f.required) 'required',
        if (f.nullable) 'nullable',
        if (f.collection) 'collection',
        if (f.derived) 'DERIVED',
        if (f.defaultValue != null) 'default=${f.defaultValue}',
      ].join(' · ');
  final b = StringBuffer()
    ..writeln('# ${e.entity} — data decomposition')
    ..writeln()
    ..writeln('> Auto-generated by `tools/atom/decompose` (data). Read-only —')
    ..writeln('> re-run the decomposer. Module: `${m.module}` · `${m.sourcePath}`.')
    ..writeln()
    ..writeln('- **kind:** ${e.kind}')
    ..writeln()
    ..writeln('## עצם · object (fields)')
    ..writeln('| field | type | flags |')
    ..writeln('|---|---|---|');
  for (final f in e.fields) {
    b.writeln('| `${f.name}` | `${f.type}` | ${flags(f).isEmpty ? '—' : flags(f)} |');
  }
  b
    ..writeln()
    ..writeln('## חיבורים · connections (relations)');
  if (e.relations.isEmpty) {
    b.writeln('- _none_');
  } else {
    for (final r in e.relations) {
      b.writeln('- **${r.kind}** `${r.field}` → `${r.ref}`${r.collection ? ' (many)' : ''}');
    }
  }
  b
    ..writeln()
    ..writeln('## התנהגות · behaviour')
    ..writeln('- **decoders:** ${e.decoders.isEmpty ? '_none_' : e.decoders.map((d) => '`$d`').join(' · ')}'
        '${e.tolerantDecoder ? '  ⚠️ TOLERANT (malformed input degrades silently — validation debt)' : ''}')
    ..writeln('- **methods:** ${e.behaviour.isEmpty ? '_none_' : e.behaviour.map((x) => '`$x`').join(' · ')}')
    ..writeln()
    ..writeln('## חוזה · contract')
    ..writeln('- **required:** ${e.required.isEmpty ? '_none_' : e.required.map((x) => '`$x`').join(' · ')}')
    ..writeln('- **defaults:** ${e.defaults.isEmpty ? '_none_' : e.defaults.entries.map((x) => '`${x.key}=${x.value}`').join(' · ')}');
  if (e.invariants.isNotEmpty) {
    b.writeln('- **invariants:**');
    for (final inv in e.invariants) {
      b.writeln('  - $inv');
    }
  }
  return b.toString();
}
