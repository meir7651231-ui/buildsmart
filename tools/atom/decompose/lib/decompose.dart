/// Render one async [module] — `module.async.json` + `<module>.async.md`.
Map<String, String> renderAsyncFiles(AsyncModuleDecomposition module) {
  final b = StringBuffer()
    ..writeln('# ${module.module} — async decomposition')
    ..writeln()
    ..writeln('> Auto-generated by `tools/atom/decompose` (async). Read-only —')
    ..writeln('> re-run the decomposer. Source: `${module.sourcePath}`.')
    ..writeln()
    ..writeln('## Providers')
    ..writeln('| provider | kind | async? | backing | line |')
    ..writeln('|---|---|---|---|---|');
  for (final pr in module.providers) {
    b.writeln('| `${pr.name}` | ${pr.kind} | ${pr.async ? '⏳ async' : 'sync'} '
        '| ${pr.backing} | ${pr.line} |');
  }
  b
    ..writeln()
    ..writeln('## Consumers (`.when`)');
  if (module.consumers.isEmpty) {
    b.writeln('- _none_');
  } else {
    b
      ..writeln('| source | line | states | error→empty (#3) | empty-in-data |')
      ..writeln('|---|---|---|---|---|');
    for (final c in module.consumers) {
      final states = [
        if (c.loading) 'loading',
        if (c.error) 'error',
        if (c.data) 'data'
      ].join('·');
      b.writeln('| `${c.source}` | ${c.line} | $states '
          '| ${c.errorFoldsToEmpty ? '✅' : '—'} '
          '| ${c.emptyInData ? '✅' : '—'} |');
    }
  }
  b
    ..writeln()
    ..writeln('## Typed exceptions');
  if (module.exceptions.isEmpty) {
    b.writeln('- _none_');
  } else {
    for (final e in module.exceptions) {
      b.writeln('- `${e.name}` (line ${e.line}) · ${e.throwSites} throw-site(s)');
    }
  }
  return <String, String>{
    'module.async.json': '${_json.convert(module.toJson())}\n',
    '${_slug(module.module)}.async.md': b.toString(),
  };
}

