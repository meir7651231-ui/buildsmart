  b
    ..writeln()
    ..writeln('## `.when` consumers — the modeled states')
    ..writeln()
    ..writeln('| source | states | error→empty (#3) | empty-in-data |')
    ..writeln('|---|---|---|---|');
  for (final c in overview.consumers) {
