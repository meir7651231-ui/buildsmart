    ..writeln('- **`.when` consumers:** ${overview.consumers.length} '
        '(${overview.errorFoldedConsumers} fold error→empty · HARD RULE #3)')
    ..writeln('- **typed exceptions:** ${overview.exceptions.length}')
    ..writeln()
    ..writeln('## The split (step 85)')
    ..writeln()
    ..writeln('The catalog / cart are **synchronous const data** — no `AsyncValue`, '
        'no loading, empty is ad-hoc. Only **firestore / functions** flow through '
        '`AsyncValue` + `.when`. There is **no uniform async contract**; a sync '
